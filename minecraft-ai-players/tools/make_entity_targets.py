"""Writes the AI parts of behavior_pack/entities/ai_player.json (targeting, modes)
and behavior_pack/scripts/gather_data.js (what the Resource AI can gather).

The Script API can't set a mob's target directly, so the script "points" each AI at a
target with tags, using numbered brain slots (one per loaded AI):
  aip_s<k>  on the AI that uses slot k
  aip_h<k>  on the entity that AI should hunt
  aip_a<k>  on every entity that AI must never attack (owner, allies, friendly AIs)
Run: python3 tools/make_entity_targets.py"""
import json
from pathlib import Path

SLOTS = 16
PATH = Path(__file__).resolve().parent.parent / "behavior_pack/entities/ai_player.json"


def not_friendly():
    """True unless the candidate carries the ally tag for this AI's slot."""
    return {"all_of": [
        {"any_of": [
            {"test": "has_tag", "subject": "self", "operator": "!=", "value": f"aip_s{k}"},
            {"test": "has_tag", "subject": "other", "operator": "!=", "value": f"aip_a{k}"},
        ]} for k in range(SLOTS)
    ] + [{"test": "is_owner", "subject": "other", "operator": "!=", "value": True}]}


# ---------------------------------------------------------------- gathering
# Blocks the Resource AI can gather. tool: which tool type is needed (or helps), tier: minimum
# pickaxe tier (0 wood/gold, 1 stone, 2 iron, 3 diamond), required: True if it drops nothing without it.
WOODS = ["oak", "spruce", "birch", "jungle", "acacia", "dark_oak", "mangrove", "cherry", "pale_oak"]
GATHER = {}
for w in WOODS:
    GATHER[f"minecraft:{w}_log"] = {"focus": "Wood", "drop": f"minecraft:{w}_log", "hardness": 2, "tool": "axe", "tier": 0, "required": False}
for w in ("crimson", "warped"):
    GATHER[f"minecraft:{w}_stem"] = {"focus": "Wood", "drop": f"minecraft:{w}_stem", "hardness": 2, "tool": "axe", "tier": 0, "required": False}
for block, drop, hardness in (
    ("stone", "cobblestone", 1.5), ("granite", "granite", 1.5), ("diorite", "diorite", 1.5),
    ("andesite", "andesite", 1.5), ("tuff", "tuff", 1.5), ("deepslate", "cobbled_deepslate", 3),
):
    GATHER[f"minecraft:{block}"] = {"focus": "Stone", "drop": f"minecraft:{drop}", "hardness": hardness, "tool": "pickaxe", "tier": 0, "required": True}
for ore, drop, lo, hi, tier in (
    ("coal", "coal", 1, 1, 0), ("copper", "raw_copper", 2, 5, 1), ("iron", "raw_iron", 1, 1, 1),
    ("lapis", "lapis_lazuli", 4, 9, 1), ("gold", "raw_gold", 1, 1, 2), ("redstone", "redstone", 4, 5, 2),
    ("diamond", "diamond", 1, 1, 2), ("emerald", "emerald", 1, 1, 2),
):
    for prefix, hardness in (("", 3), ("deepslate_", 4.5)):
        GATHER[f"minecraft:{prefix}{ore}_ore"] = {"focus": "Ores", "drop": f"minecraft:{drop}", "min": lo, "max": hi, "hardness": hardness, "tool": "pickaxe", "tier": tier, "required": True}
for lit in ("minecraft:lit_redstone_ore", "minecraft:lit_deepslate_redstone_ore"):
    GATHER[lit] = dict(GATHER[lit.replace("lit_", "")])
GATHER["minecraft:nether_gold_ore"] = {"focus": "Ores", "drop": "minecraft:gold_nugget", "min": 2, "max": 6, "hardness": 3, "tool": "pickaxe", "tier": 0, "required": True}
GATHER["minecraft:quartz_ore"] = {"focus": "Ores", "drop": "minecraft:quartz", "hardness": 3, "tool": "pickaxe", "tier": 0, "required": True}
GATHER["minecraft:ancient_debris"] = {"focus": "Ores", "drop": "minecraft:ancient_debris", "hardness": 30, "tool": "pickaxe", "tier": 3, "required": True}
# Sugar cane farm materials (only gathered while collecting for a farm).
for sand in ("sand", "red_sand"):
    GATHER[f"minecraft:{sand}"] = {"focus": "Sand", "drop": f"minecraft:{sand}", "hardness": 0.5, "tool": "shovel", "tier": 0, "required": False}
GATHER["minecraft:reeds"] = {"focus": "Cane", "drop": "minecraft:sugar_cane", "hardness": 0.1, "tool": "none", "tier": 0, "required": False}

# What the Resource AI can be told to get, and which blocks each one means.
FOCUSES = ["Trees", "Caves"]
FOCUS_TYPES = {"Trees": "Wood", "Caves": "Ores"}
OLD_FOCUSES = ["Wood", "Stone", "Ores", "Everything"]  # before v1.16
GATHER_JS = PATH.parent.parent / "scripts/gather_data.js"


def focus_blocks(focus):
    return [b for b, info in GATHER.items() if focus == "Everything" or info["focus"] == focus]


def write_gather_data():
    js = (
        "// Generated by tools/make_entity_targets.py. Do not edit by hand.\n"
        "/** @type {Record<string, { focus: string, drop: string, min?: number, max?: number, hardness: number, tool: string, tier: number, required: boolean }>} */\n"
        f"export const GATHER = {json.dumps(GATHER, indent=2)};\n\n"
        f"export const FOCUSES = {json.dumps(FOCUSES + ['Nothing'])};\n\n"
        "/** Which GATHER blocks each focus gets. @type {Record<string, string>} */\n"
        f"export const FOCUS_TYPES = {json.dumps(FOCUS_TYPES)};\n"
    )
    GATHER_JS.write_text(js)


def main():
    e = json.loads(PATH.read_text())
    ent = e["minecraft:entity"]
    g, c, ev = ent["component_groups"], ent["components"], ent["events"]
    safe = {"filters": not_friendly()}

    follow = {"priority": 5, "speed_multiplier": 1.2, "start_distance": 6, "stop_distance": 2}
    g["aip:role_fighter"] = {
        # The script's chosen target (tagged aip_h<slot>) comes first.
        "minecraft:behavior.nearest_attackable_target": {
            "priority": 1, "must_see": False, "reselect_targets": True, "within_radius": 32.0,
            "scan_interval": 5,
            "entity_types": [{"filters": {"all_of": [
                {"test": "has_tag", "subject": "self", "value": f"aip_s{k}"},
                {"test": "has_tag", "subject": "other", "value": f"aip_h{k}"},
            ]}, "max_dist": 32} for k in range(SLOTS)],
        },
        # Instant reactions while the script catches up. Never against friends.
        "minecraft:behavior.owner_hurt_by_target": {"priority": 2, "entity_types": safe},
        "minecraft:behavior.owner_hurt_target": {"priority": 3, "entity_types": safe},
        "minecraft:health": {"value": 20, "max": 20},  # same as a player
        "minecraft:attack": {"damage": 6},
    }
    g["aip:role_resource"] = {"minecraft:health": {"value": 20, "max": 20}, "minecraft:attack": {"damage": 3}}
    # Modes. mark_variant is just a harmless marker so each group has a component.
    g["aip:fighter_follow"] = {"minecraft:behavior.follow_owner": follow, "minecraft:mark_variant": {"value": 0}}
    g["aip:fighter_guard"] = {"minecraft:mark_variant": {"value": 1}}
    # Resource AI directions: strictly follow its owner, or wander on its own to gather.
    g["aip:resource_follow"] = {"minecraft:behavior.follow_owner": follow}
    g["aip:resource_wander"] = {"minecraft:behavior.random_stroll": {"priority": 7, "speed_multiplier": 0.9, "xz_dist": 12, "y_dist": 4}}
    ev["aip:resource_follow"] = {"remove": {"component_groups": ["aip:resource_wander"]}, "add": {"component_groups": ["aip:resource_follow"]}}
    ev["aip:resource_wander"] = {"remove": {"component_groups": ["aip:resource_follow"]}, "add": {"component_groups": ["aip:resource_wander"]}}
    # Strip mining: the script moves it through its tunnel, so neither follow nor wander.
    ev["aip:resource_stay"] = {"remove": {"component_groups": ["aip:resource_follow", "aip:resource_wander"]}}

    # Upgraded (at the Coder): can't burn and walks through lava. No potion effect, so no bubbles.
    g["aip:upgraded"] = {"minecraft:fire_immune": {}}
    ev["aip:upgrade"] = {"add": {"component_groups": ["aip:upgraded"]}}

    # Gathering is done entirely by the script (gather.js walks the AI next to the block and mines it).
    # Older versions used move_to_block here, which can't reach solid blocks like logs: remove it.
    for focus in OLD_FOCUSES:
        g.pop(f"aip:gather_{focus.lower()}", None)
        ev.pop(f"aip:gather_{focus.lower()}", None)
    ev.pop("aip:gather_off", None)
    # Low health: run from danger while the script heals it.
    g["aip:retreating"] = {"minecraft:behavior.avoid_mob_type": {
        "priority": 1,
        "entity_types": [{"filters": {"any_of": [
            {"test": "is_family", "subject": "other", "value": "monster"},
            {"all_of": [
                {"test": "is_family", "subject": "other", "value": "player"},
                {"test": "is_owner", "subject": "other", "operator": "!=", "value": True},
            ]},
        ]}, "max_dist": 10, "walk_speed_multiplier": 1.1, "sprint_speed_multiplier": 1.4}],
    }}
    ev["aip:retreat"] = {"add": {"component_groups": ["aip:retreating"]}}
    ev["aip:recovered"] = {"remove": {"component_groups": ["aip:retreating"]}}

    c["minecraft:behavior.hurt_by_target"] = {"priority": 4, "entity_types": safe}
    c["minecraft:health"] = {"value": 20, "max": 20}

    # Fighting style, switched by the script: melee (sword, axe, fists) or ranged (bow/crossbow + arrows).
    c.pop("minecraft:behavior.melee_attack", None)
    # Melee sprints at the target (1.45x speed) and keeps hitting.
    g["aip:melee"] = {"minecraft:behavior.melee_attack": {"priority": 3, "speed_multiplier": 1.45, "track_target": True}}
    # Ranged: this behavior keeps the AI at bow range (up to 25 blocks). The script fires the actual
    # arrows (aiming ahead of moving targets) and removes the plain arrows this behavior shoots.
    g["aip:ranged"] = {
        "minecraft:shooter": {"def": "minecraft:arrow"},
        "minecraft:behavior.ranged_attack": {
            "priority": 3, "speed_multiplier": 1.0, "attack_interval_min": 1.0,
            "attack_interval_max": 2.0, "attack_radius": 25.0,
        },
    }
    ev["aip:use_melee"] = {"remove": {"component_groups": ["aip:ranged"]}, "add": {"component_groups": ["aip:melee"]}}
    ev["aip:use_ranged"] = {"remove": {"component_groups": ["aip:melee"]}, "add": {"component_groups": ["aip:ranged"]}}
    spawn = ev["minecraft:entity_spawned"]["add"]["component_groups"]
    if "aip:melee" not in spawn:
        spawn.append("aip:melee")
    PATH.write_text(json.dumps(e, indent=2) + "\n")
    write_gather_data()
    print("wrote targeting for", SLOTS, "slots and", len(GATHER), "gatherable blocks")


if __name__ == "__main__":
    main()
